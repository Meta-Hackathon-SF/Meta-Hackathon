import type { ModelEvidence, PublicPlanCard } from "./types";

export function formatWhen(start: string, end: string, timeZone: string, locale?: string): string {
  const s = new Date(start);
  const e = new Date(end);
  if (Number.isNaN(s.getTime()) || Number.isNaN(e.getTime())) return "Time unavailable";
  const day = new Intl.DateTimeFormat(locale, { timeZone, weekday: "short", month: "short", day: "numeric" }).format(s);
  const time = new Intl.DateTimeFormat(locale, { timeZone, hour: "numeric", minute: "2-digit" });
  const zone =
    new Intl.DateTimeFormat(locale, { timeZone, timeZoneName: "short" })
      .formatToParts(s)
      .find((p) => p.type === "timeZoneName")?.value ?? timeZone;
  return `${day}, ${time.format(s)} – ${time.format(e)} ${zone}`;
}

export function durationMinutes(start: string, end: string): number {
  return Math.round((new Date(end).getTime() - new Date(start).getTime()) / 60000);
}

export function formatCost(minor: number, currency: string, locale?: string): string {
  if (minor === 0) return "Free";
  const fmt = new Intl.NumberFormat(locale, { style: "currency", currency });
  const digits = fmt.resolvedOptions().maximumFractionDigits ?? 2;
  return `${fmt.format(minor / 10 ** digits)} per person`;
}

export type EvidenceKind = "live" | "replay" | "fixture";

/** Fixture doubles are labeled replay + "fixture:" model prefix until D005 lands. */
export function evidenceKind(e: ModelEvidence): EvidenceKind {
  if (e.model.startsWith("fixture:")) return "fixture";
  return e.source;
}

export function evidenceLabel(e: ModelEvidence): string {
  const kind = evidenceKind(e);
  if (kind === "fixture") return "Fixture · scripted, not generated by Muse";
  const secs = (e.latencyMs / 1000).toFixed(1);
  if (kind === "replay") return `Replay of a saved run · ${e.model}`;
  return `Live · ${e.model} · ${secs}s`;
}

export interface FieldChange {
  field: "title" | "activity" | "when" | "where" | "cost";
  label: string;
  before: string;
  after: string;
  material: boolean;
}

/** Public before/after for a revision. Time, place and cost are material. */
export function diffPlans(prev: PublicPlanCard, next: PublicPlanCard, locale?: string): FieldChange[] {
  const out: FieldChange[] = [];
  const push = (field: FieldChange["field"], label: string, before: string, after: string, material: boolean) => {
    if (before !== after) out.push({ field, label, before, after, material });
  };
  push("when", "When", formatWhen(prev.start, prev.end, prev.timeZone, locale), formatWhen(next.start, next.end, next.timeZone, locale), true);
  push("where", "Where", prev.venue.name, next.venue.name, true);
  push("cost", "Cost", formatCost(prev.costPerPersonMinor, prev.currency, locale), formatCost(next.costPerPersonMinor, next.currency, locale), true);
  push("title", "Quest", prev.title, next.title, false);
  push("activity", "Activity", prev.activity, next.activity, false);
  return out;
}
